(function(){

  function initContactForm(){

    var form = document.getElementById('contactForm');
    var submitBtn = document.getElementById('submitBtn');
    var formStatus = document.getElementById('formStatus');
    var modal = document.getElementById('successModal');
    var modalClose = document.getElementById('modalCloseBtn');

    var dateInput = document.querySelector('input[name="preferred_date"]');
    if(dateInput){
      var today = new Date();
      var yyyy = today.getFullYear();
      var mm = String(today.getMonth() + 1).padStart(2, '0');
      var dd = String(today.getDate()).padStart(2, '0');
      dateInput.min = yyyy + '-' + mm + '-' + dd;
    }

    if(form){
      form.addEventListener('submit', function(e){
        e.preventDefault();

        var originalText = submitBtn.innerHTML;
        submitBtn.disabled = true;
        submitBtn.innerHTML = '<i class="fas fa-spinner fa-spin"></i> <span>Sending...</span>';

        if(formStatus){
          formStatus.style.display = 'none';
          formStatus.className = 'form-status';
        }

        var formData = new FormData(form);
        var object = {};
        formData.forEach(function(value, key){
          object[key] = value;
        });

        fetch('https://api.web3forms.com/submit', {
          method:'POST',
          headers:{
            'Content-Type':'application/json',
            'Accept':'application/json'
          },
          body:JSON.stringify(object)
        })
        .then(function(response){
          return response.json();
        })
        .then(function(result){
          if(result.success){
            if(modal) modal.classList.add('active');
            form.reset();
          }else{
            if(formStatus){
              formStatus.className = 'form-status error';
              formStatus.textContent = result.message || 'Something went wrong. Please try again or contact us via WhatsApp.';
            }
          }
        })
        .catch(function(){
          if(formStatus){
            formStatus.className = 'form-status error';
            formStatus.textContent = 'Connection error. Please check your internet and try again.';
          }
        })
        .then(function(){
          submitBtn.disabled = false;
          submitBtn.innerHTML = originalText;
        });
      });
    }

    if(modalClose){
      modalClose.addEventListener('click', function(){
        if(modal) modal.classList.remove('active');
      });
    }

    if(modal){
      modal.addEventListener('click', function(e){
        if(e.target === modal) modal.classList.remove('active');
      });
    }
  }

  if(document.readyState === 'loading'){
    document.addEventListener('DOMContentLoaded', initContactForm);
  }else{
    initContactForm();
  }

})();
</script>

